from langgraph.graph import StateGraph, END
from langgraph.checkpoint.memory import MemorySaver
from typing import TypedDict, List, Dict

# 1. State Schema: Models a physical journal version history
class JournalState(TypedDict):
    sequence_id: str
    target_moves: List[str]       # e.g., ["pirouette_right", "sidesplit_right", "highkick_right"]
    version_history: List[Dict]   # Tracks every attempt: {"version": 1, "human_notes": "...", "status": "..."}
    current_version: int
    system_tags: List[str]        # Auto-generated by AI to help you query the sequence later

def init_session(state: JournalState) -> JournalState:
    """Initializes the diary ledger for the acrobatic sequence."""
    return {
        **state,
        "current_version": len(state.get("version_history", [])) + 1,
        "system_tags": state.get("system_tags", [])
    }

def human_execution_checkpoint(state: JournalState) -> JournalState:
    """
    The Human-in-the-Loop Node. 
    LangGraph will pause right here and wait for you to type your training journal entry.
    """
    # This node acts as an interrupt gate. When you resume with your notes,
    # they pass directly into the graph state.
    return state

def ai_journal_processor(state: JournalState) -> JournalState:
    """The Agentic Phase: Analyzes your notes, versions the data, and appends query tags."""
    from acrochoreo.llm_client import ask_ai
    
    latest_history = state["version_history"][-1]
    human_notes = latest_history.get("human_notes", "")
    
    # AI reads your journal entry to generate semantic tags for future querying
    ai_analysis = ask_ai(
        f"Analyze this acrobatic journal entry for sequence {state['target_moves']}.\n"
        f"Human Notes: {human_notes}\n"
        f"Generate 3-4 comma-separated search tags (e.g., balance-issue, fluid-transition, hip-flexibility)."
    )
    
    # Parse tags and clean up
    new_tags = [tag.strip().lower() for tag in ai_analysis.split(",") if tag.strip()]
    updated_tags = list(set(state["system_tags"] + new_tags))
    
    return {
        **state,
        "system_tags": updated_tags
    }

# 2. Building the Interrupted Graph
workflow = StateGraph(JournalState)

workflow.add_node("init_session", init_session)
workflow.add_node("human_checkpoint", human_execution_checkpoint)
workflow.add_node("ai_processor", ai_journal_processor)

workflow.set_entry_point("init_session")
workflow.add_edge("init_session", "human_checkpoint")
workflow.add_edge("human_checkpoint", "ai_processor")

# If the last human note says you want to try again, it loops back to step up a new version
def route_next_attempt(state: JournalState) -> str:
    if state["version_history"][-1].get("status") == "retry":
        return "init_session"
    return END

workflow.add_conditional_edges("ai_processor", route_next_attempt, {"init_session": "init_session", "end": END})

# 3. Memory Saver provides the time-travel & version database
memory = MemorySaver()
app = workflow.compile(checkpointer=memory, interrupt_before=["human_checkpoint"])

